"""Embed a Space Invaders machine ROM (up to 8 KB) for the Pico build.

    py -3 tools/embed_rom.py machine/invaders_test.rom src/inv_rom_test.pmi
    py -3 tools/embed_rom.py demo/demo_roms src/inv_rom_demo.pmi

A folder is the compiler's ROM-chip output: invaders.h, .g, .f, .e (2 KB
each, MAME's layout), joined in that order.

Writes a DataSection with the label InvRom and the constant #INV_ROM_SIZE.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1])
if src.is_dir():
    rom = b''.join((src / f'invaders.{c}').read_bytes() for c in 'hgfe')
else:
    rom = src.read_bytes()
out = Path(sys.argv[2])
if not 0 < len(rom) <= 0x2000:
    raise SystemExit(f'{sys.argv[1]}: {len(rom)} bytes; a machine ROM is 1 to 8192 bytes')
lines = [f'; Generated by tools/embed_rom.py from {Path(sys.argv[1]).name}. Do not edit.',
         f'#INV_ROM_SIZE = {len(rom)}', 'DataSection', 'InvRom:']
for i in range(0, len(rom), 32):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in rom[i:i + 32]))
lines.append('EndDataSection')
out.write_text('\n'.join(lines) + '\n')
print(f'{out}: {len(rom)} bytes')
