"""Generate the desktop (PureBasic, C back end, x64) 8080 core from the same
opcode semantics as the Pico cores.

    py -3 tools/generate_desktop.py

Writes desktop/i8080core.pbi. #CPU_DISPATCH selects the dispatch:
  0  labels-as-values: a 256-entry table of C label addresses and a computed
     goto at the end of every handler (inline C through the C back end)
  1  a 256-entry table of procedure addresses called from a loop
The desktop core always budgets in cycles and also counts instructions.
"""
from pathlib import Path
import generate as g

ROOT = Path(__file__).resolve().parents[1]

HEADER = '''; Generated by tools/generate_desktop.py from the opcode table in
; tools/generate.py (the same semantics as the Pico cores). Edit the generator.
;
; Intel 8080 core for the desktop (PureBasic, C back end). Before including:
;   #CPU_DISPATCH = 0   ; 0 computed goto (labels as values), 1 procedure table
;   #CPU_MEMMAP   = 0   ; 1: data reads/writes through CpuMemMap and the traps
; The program supplies CpuPortIn(port) / CpuPortOut(port, value) and, with
; #CPU_MEMMAP = 1, CpuReadTrap(address) / CpuWriteTrap(address, value), and
; declares them before this file is included (PureBasic needs that).
; CpuRun(n) budgets n clock cycles and returns the cycles consumed; CpuInstr
; counts instructions. Everything else is as in the Pico core's README.
EnableExplicit
Global Dim M.a(65535)
Global Dim Parity.a(255)
Global Dim CpuMemMap.a(255)
Global Dim CycTab.a(255)
Global Dim OpTable.i(255)
Global CpuPC.i, CpuA.i, CpuBC.i, CpuDE.i, CpuHL.i, CpuSP.i
Global FR.i, FC.i, FA.i
Global CpuIE.i, CpuHalted.i, CpuEiDelay.i, CpuYield.i, CpuInstr.q
Global Res.i, Left.i, Budget.i, ParityReady.i
Global Ea.i, Value.i, Tmp.i, MemVal.i

CompilerIf #CPU_MEMMAP = 1
Procedure.i CpuRead(adr.i)
  If CpuMemMap(adr >> 8) & 1
    ProcedureReturn M(adr)
  EndIf
  ProcedureReturn CpuReadTrap(adr) & 255
EndProcedure
Procedure CpuWrite(adr.i, v.i)
  If CpuMemMap(adr >> 8) & 2
    M(adr) = v
  Else
    CpuWriteTrap(adr, v)
  EndIf
EndProcedure
Macro Rd(adr) : CpuRead(adr) : EndMacro
Macro Wr(adr, v) : CpuWrite(adr, v) : EndMacro
CompilerElse
Macro Rd(adr) : M(adr) : EndMacro
Macro Wr(adr, v) : M(adr) = v : EndMacro
CompilerEndIf

Macro Push16(v)
  Res = (CpuSP - 2) & $FFFF
  CpuSP = Res
  Wr((Res + 1) & $FFFF, (v) >> 8)
  Wr(Res, (v) & 255)
EndMacro
Macro Pop16(v)
  Res = Rd((CpuSP + 1) & $FFFF) << 8
  v = Res | Rd(CpuSP)
  CpuSP = (CpuSP + 2) & $FFFF
EndMacro
Macro Charge(c)
  Left = Left - c
EndMacro
Macro PackFlags(v)
  v = 2 | ((FA ! FR) & $10) | ((FC >> 8) & 1) | Parity((FR ! (FR >> 8)) & 255)
  If FR & $8080
    v = v | $80
  EndIf
  If (FR & 255) = 0
    v = v | $40
  EndIf
EndMacro
Macro SetFlags(p)
  MemVal = p
  FC = (MemVal & 1) << 8
  If MemVal & $40
    FR = (MemVal & $80) << 8
  Else
    FR = (MemVal & $80) | 1
  EndIf
  If Parity((FR ! (FR >> 8)) & 255) <> (MemVal & 4)
    FR = FR | $100
  EndIf
  FA = (MemVal & $10) ! FR
EndMacro

Procedure CpuInitTables()
  Protected i.i, b.i, n.i, cyc.a
  For i = 0 To 255
    n = 0
    For b = 0 To 7
      n = n + ((i >> b) & 1)
    Next
    If n & 1
      Parity(i) = 0
    Else
      Parity(i) = 4
    EndIf
  Next
  Restore CpuCycleData
  For i = 0 To 255
    Read.a cyc
    CycTab(i) = cyc
  Next
  ParityReady = 1
EndProcedure
Procedure.i CpuFlags()
  Protected v.i
  PackFlags(v)
  ProcedureReturn v
EndProcedure
Procedure CpuSetFlags(p.i)
  SetFlags(p)
EndProcedure
Procedure CpuReset()
  If ParityReady = 0
    CpuInitTables()
  EndIf
  CpuPC = 0 : CpuA = 0 : CpuBC = 0 : CpuDE = 0 : CpuHL = 0 : CpuSP = 0
  CpuSetFlags(2)
  CpuIE = 0 : CpuHalted = 0 : CpuEiDelay = 0 : CpuYield = 0 : CpuInstr = 0
EndProcedure
Procedure.i CpuInterrupt(opcode.i)
  If opcode < 0 Or opcode > 255
    ProcedureReturn 0
  EndIf
  If (opcode & $C7) <> $C7
    ProcedureReturn 0
  EndIf
  If CpuIE = 0 Or CpuEiDelay <> 0
    ProcedureReturn 0
  EndIf
  CpuIE = 0
  CpuHalted = 0
  Push16(CpuPC)
  CpuPC = opcode & $38
  ProcedureReturn 11
EndProcedure
'''


def handler_lines(op):
    name, lines, tail = g.body(op)
    return name, lines, tail, g.CYC[op]


def goto_core():
    out = ['CompilerIf #CPU_DISPATCH = 0', 'Procedure.i CpuRun(n.i)',
           '  If n <= 0', '    ProcedureReturn 0', '  EndIf',
           '  If CpuHalted', '    ProcedureReturn n', '  EndIf',
           '  CpuEiDelay = 0 : CpuYield = 0', '  Budget = n : Left = n']
    labels = ', '.join(f'&&op{op:02x}' for op in range(256))
    out.append(f'  ! static void *i8080_tbl[256] = {{{labels}}};')
    dispatch = ['  Tmp = M(CpuPC)', '  CpuPC = (CpuPC + 1) & $FFFF', '  ! goto *i8080_tbl[g_tmp];']
    out += dispatch
    for op in range(256):
        name, lines, tail, c = handler_lines(op)
        out.append(f'  ! op{op:02x}:; // {name}, {c} cycles')
        out += ['  ' + s for s in lines]
        out.append('  CpuInstr + 1')
        out.append(f'  Left - {c}')
        if tail == 'next':
            out += ['  If Left <= 0', '    Goto Done', '  EndIf'] + dispatch
        elif tail == 'io':
            out += ['  If Left <= 0 Or CpuYield', '    Goto Done', '  EndIf'] + dispatch
        elif tail == 'ei':
            out += ['  If Left <= 0', '    CpuEiDelay = 1', '    Goto Done', '  EndIf'] + dispatch
        elif tail == 'hlt':
            out += ['  CpuHalted = 1', '  If Left > 0', '    Left = 0', '  EndIf', '  Goto Done']
    out += ['  Done:', '  CpuYield = 0', '  ProcedureReturn Budget - Left', 'EndProcedure', 'CompilerEndIf']
    return out


def table_core():
    out = ['CompilerIf #CPU_DISPATCH = 1']
    for op in range(256):
        name, lines, tail, c = handler_lines(op)
        out.append(f'Procedure Op{op:02X}() ; {name}, {c} cycles (charged by CpuRun)')
        out += ['  ' + s for s in lines]
        if tail == 'ei':
            out += ['  If Left <= 0', '    CpuEiDelay = 1', '  EndIf']
        elif tail == 'hlt':
            out += ['  CpuHalted = 1', '  If Left > 0', '    Left = 0', '  EndIf']
        out.append('EndProcedure')
    out += ['Procedure CpuInitOpTable()']
    out += [f'  OpTable(${op:02X}) = @Op{op:02X}()' for op in range(256)]
    out += ['EndProcedure',
            'Procedure.i CpuRun(n.i)',
            '  If n <= 0', '    ProcedureReturn 0', '  EndIf',
            '  If CpuHalted', '    ProcedureReturn n', '  EndIf',
            '  If OpTable(0) = 0', '    CpuInitOpTable()', '  EndIf',
            '  CpuEiDelay = 0 : CpuYield = 0', '  Budget = n : Left = n',
            '  While Left > 0 And CpuYield = 0', '    Tmp = M(CpuPC)', '    CpuPC = (CpuPC + 1) & $FFFF',
            '    Left - CycTab(Tmp)', '    CpuInstr + 1', '    CallFunctionFast(OpTable(Tmp))',
            '    If CpuHalted', '      Break', '    EndIf', '  Wend',
            '  CpuYield = 0', '  ProcedureReturn Budget - Left', 'EndProcedure', 'CompilerEndIf']
    return out


def length(op):
    x, y, z = op >> 6, (op >> 3) & 7, op & 7
    if x == 0:
        if z == 1 and y & 1 == 0: return 3          # LXI
        if z == 2 and y >= 4: return 3              # SHLD LHLD STA LDA
        if z == 6: return 2                         # MVI
    if x == 3:
        if z in (2, 4): return 3                    # Jcc Ccc
        if z == 3 and y in (0, 1): return 3         # JMP
        if z == 3 and y in (2, 3): return 2         # OUT IN
        if z == 5 and y & 1: return 3               # CALL
        if z == 6: return 2                         # ALU immediate
    return 1


def main():
    out = HEADER.splitlines() + [''] + goto_core() + [''] + table_core() + ['']
    out += ['DataSection', '  CpuCycleData:']
    for row in range(0, 256, 16):
        out.append('  Data.a ' + ', '.join(str(g.CYC[op]) for op in range(row, row + 16)))
    out.append('  CpuLengthData:')
    for row in range(0, 256, 16):
        out.append('  Data.a ' + ', '.join(str(length(op)) for op in range(row, row + 16)))
    out.append('  CpuMnemonicData:')
    for op in range(256):
        name = g.body(op)[0].replace(' (undocumented)', '*')
        out.append(f'  Data.s "{name}"')
    out += ['EndDataSection', '']
    text = '\n'.join(out) + '\n'
    (ROOT / 'desktop').mkdir(exist_ok=True)
    (ROOT / 'desktop' / 'i8080core.pbi').write_text(text, encoding='utf-8')
    print(f'desktop/i8080core.pbi: {text.count(chr(10))} lines')


if __name__ == '__main__':
    main()
