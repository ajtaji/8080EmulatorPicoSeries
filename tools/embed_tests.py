"""Embed the fetched CP/M diagnostics as PureMetal DataSection tables."""
from pathlib import Path
root = Path(__file__).resolve().parents[1] / 'Diagnostics'
lines = ['; Generated by tools/embed_tests.py from Diagnostics/upstream. Not committed.']
tests = [('Tst8080', 'TST8080.COM'), ('Pre8080', '8080PRE.COM'), ('Cputest', 'CPUTEST.COM'), ('Exm8080', '8080EXM.COM')]
for label, name in tests:
    lines.append(f'#{label.upper()}_SIZE = {(root / "upstream" / name).stat().st_size}')
lines.append('DataSection')
for label, name in tests:
    data = (root / 'upstream' / name).read_bytes()
    lines.append(label + ':')
    for start in range(0, len(data), 32):
        lines.append('  Data.a ' + ','.join(f'${x:02X}' for x in data[start:start + 32]))
lines.append('EndDataSection')
for name in ('test_data.pico', 'test_data.pico2'):
    (root / name).write_text('\n'.join(lines) + '\n')
print('wrote Diagnostics/test_data.pico and .pico2')
